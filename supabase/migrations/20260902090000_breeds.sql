-- CRU-102. The breeds table, and its seed.
--
-- The client does NOT read this table. The same list ships in the app bundle
-- as a static asset keyed by these ids -- see CRU-103 for the cost reasoning.
-- The table earns its place by making pets.breed_id a real foreign key, and as
-- what future breed-keyed content reads.
--
-- The data is Wikidata, which is CC0. See docs/research/breed-data-sources.md
-- and scripts/build-breeds.ts, which is what regenerates data/breeds.json.

create type public.breed_species as enum ('dog', 'cat');

-- No wikidata_qid column. Nothing reads it at runtime, so it would be a column
-- kept correct for no return. The Q-ids live in data/breeds.json, which is
-- where a refresh happens.
create table public.breeds (
  id uuid primary key,
  species public.breed_species not null,
  name text not null,
  -- How a breed leaves the list without breaking the pets that point at it.
  is_active boolean not null default true,

  constraint breeds_name_unique_per_species unique (species, name)
);

-- Every read is "the active breeds of one species", so the partial index over
-- that pair is the only one this table needs.
create index breeds_species_name_idx
  on public.breeds (species, name)
  where is_active;

alter table public.breeds enable row level security;

-- Select only. Nobody writes this table from the app; a change is a migration.
create policy "Any signed-in member can read breeds"
on public.breeds for select
to authenticated
using ( true );

